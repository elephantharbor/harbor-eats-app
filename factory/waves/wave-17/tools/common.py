def _prompts_file(path):
    from pathlib import Path
    out, cur = {}, None
    for line in Path(path).read_text().splitlines():
        if line.startswith("## "):
            cur = line[3:].strip()
        elif cur and line.strip():
            assert cur not in out, f"{cur}: more than one prompt line"
            out[cur] = line
    return out


