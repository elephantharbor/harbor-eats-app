/**
 * Render a D1-ready SQL script from a catalog sqlite database produced by import-catalog.
 * Child rows are deleted once per recipe_version_id, then all rows for that version are inserted.
 * No BEGIN TRANSACTION wrapper (D1 remote execute is statement-by-statement).
 */

const CHILD_TABLES = [
  "catalog_ingredient",
  "catalog_step",
  "catalog_taste_tag",
  "catalog_dietary_label",
  "catalog_allergen",
  "catalog_equipment",
  "catalog_eligibility_tag",
  "catalog_image_ref",
  "catalog_provenance",
  "catalog_classification_history",
];

export function sqlLiteral(value) {
  if (value == null) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

/**
 * @param {import("node:sqlite").DatabaseSync} database
 */
export function renderStagingD1Sql(database) {
  const lines = [
    "-- Harbor Eats catalog import. Schema is migrations through 0013.",
    "-- Fresh databases only. Existing preview/prod D1 should use data/d03-classification-import.sql",
    "-- so culinary content_hash bytes already stored are not rewritten.",
    "-- Not a production apply by itself. Do not point wrangler at production D1 from staging config.",
    "-- Generated by scripts/import-catalog.mjs. No BEGIN TRANSACTION wrapper.",
    "",
  ];
  const dishes = database.prepare("SELECT * FROM catalog_dish ORDER BY slug").all();
  for (const row of dishes) {
    lines.push(
      `INSERT OR REPLACE INTO catalog_dish (dish_id, slug, title, name, description, cuisine, meal_format, primary_ingredient, texture, flavor_profile, weeknight, exploration, plate, tone, tags_json, sparks_json, chips_json, current_recipe_id, current_version_id, created_at) VALUES (${[
        row.dish_id,
        row.slug,
        row.title,
        row.name,
        row.description,
        row.cuisine,
        row.meal_format,
        row.primary_ingredient,
        row.texture,
        row.flavor_profile,
        row.weeknight,
        row.exploration,
        row.plate,
        row.tone,
        row.tags_json,
        row.sparks_json,
        row.chips_json,
        row.current_recipe_id,
        row.current_version_id,
        row.created_at,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    );
  }
  const versions = database.prepare("SELECT * FROM catalog_version ORDER BY dish_id, version_number").all();
  for (const row of versions) {
    lines.push(
      `INSERT OR REPLACE INTO catalog_version (recipe_version_id, recipe_id, dish_id, version_number, title, description, base_servings, prep_minutes, cook_minutes, total_minutes, effort_level, ingredient_complexity, classification_hash, heat, doneness, methods_json, dietary_tags_json, substitutions_json, components_json, publication_status, artifact_publication_status, visibility, household_id, content_hash, source_contract, source_path, created_at) VALUES (${[
        row.recipe_version_id,
        row.recipe_id,
        row.dish_id,
        row.version_number,
        row.title,
        row.description,
        row.base_servings,
        row.prep_minutes,
        row.cook_minutes,
        row.total_minutes,
        row.effort_level,
        row.ingredient_complexity,
        row.classification_hash,
        row.heat,
        row.doneness,
        row.methods_json,
        row.dietary_tags_json,
        row.substitutions_json,
        row.components_json,
        row.publication_status,
        row.artifact_publication_status,
        row.visibility,
        row.household_id,
        row.content_hash,
        row.source_contract,
        row.source_path,
        row.created_at,
      ]
        .map(sqlLiteral)
        .join(", ")});`
    );
  }
  lines.push("");
  lines.push("-- Child tables: one DELETE per version, then every row for that version.");
  const allVersionIds = database
    .prepare("SELECT recipe_version_id FROM catalog_version ORDER BY recipe_version_id")
    .all()
    .map((row) => row.recipe_version_id);
  for (const table of CHILD_TABLES) {
    const cols = database.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
    const rows = database
      .prepare(`SELECT * FROM ${table} ORDER BY recipe_version_id, ${table === "catalog_ingredient" ? "position" : table === "catalog_step" ? "step_number" : "rowid"}`)
      .all();
    /** @type {Map<string, object[]>} */
    const byVersion = new Map();
    for (const row of rows) {
      const versionId = row.recipe_version_id;
      if (!byVersion.has(versionId)) byVersion.set(versionId, []);
      byVersion.get(versionId).push(row);
    }
    // Every imported version gets a DELETE, including versions whose set is now EMPTY
    // (e.g. a dietary label removed by an amendment); otherwise stale rows survive on remote D1.
    const versionIds = table === "catalog_classification_history" ? [...byVersion.keys()] : allVersionIds;
    for (const versionId of [...new Set(versionIds)].sort()) {
      if (table === "catalog_classification_history") {
        // Append-only audit log: never DELETE, and skip a row whose classification transition is
        // already recorded (hardening-1 Decision Card: classification-history dedupe).
        for (const row of byVersion.get(versionId)) lines.push(classificationHistoryInsert(cols, row));
        continue;
      }
      lines.push(`DELETE FROM ${table} WHERE recipe_version_id = ${sqlLiteral(versionId)};`);
      for (const row of byVersion.get(versionId) || []) {
        lines.push(
          `INSERT INTO ${table} (${cols.join(", ")}) VALUES (${cols.map((col) => sqlLiteral(row[col])).join(", ")});`
        );
      }
    }
  }
  lines.push("");
  return lines.join("\n");
}

/**
 * Idempotent history insert: same version + same prior→new transition + same source is one row.
 * @param {string[]} cols
 * @param {object} row
 */
export function classificationHistoryInsert(cols, row) {
  const same = [
    `h.recipe_version_id = ${sqlLiteral(row.recipe_version_id)}`,
    `COALESCE(h.prior_effort_level, '') = COALESCE(${sqlLiteral(row.prior_effort_level)}, '')`,
    `COALESCE(h.prior_ingredient_complexity, '') = COALESCE(${sqlLiteral(row.prior_ingredient_complexity)}, '')`,
    `h.new_effort_level = ${sqlLiteral(row.new_effort_level)}`,
    `h.new_ingredient_complexity = ${sqlLiteral(row.new_ingredient_complexity)}`,
    `h.source = ${sqlLiteral(row.source)}`,
  ].join(" AND ");
  return `INSERT OR IGNORE INTO catalog_classification_history (${cols.join(", ")}) SELECT ${cols
    .map((col) => sqlLiteral(row[col]))
    .join(", ")} WHERE NOT EXISTS (SELECT 1 FROM catalog_classification_history h WHERE ${same});`;
}

/**
 * Split generated SQL into executable statements (skips comments and blanks).
 * @param {string} sql
 */
export function splitStagingD1Statements(sql) {
  return sql
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("--"))
    .map((line) => (line.endsWith(";") ? line.slice(0, -1) : line));
}
